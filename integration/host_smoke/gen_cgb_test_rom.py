#!/usr/bin/env python3
"""Generates cgb_test_rom.h: a 32 KiB Game Boy Color test ROM for the host tests.

It is not a game. It exists to make the emulator touch everything that decides
what a scanline looks like (both VRAM banks, tile maps, scroll, window, sprites
with 8x8 and 8x16 sizes, background and object palettes) and a few things that
only matter to timing (double speed, HDMA, the VBlank interrupt), with values
that keep changing from frame to frame. Run: python3 gen_cgb_test_rom.py > cgb_test_rom.h
"""
import sys

rom = bytearray(0x8000)
labels = {}
fix = []  # (position, label) for 1-byte relative jumps
pc = 0


def org(addr):
    global pc
    pc = addr


def emit(*b):
    global pc
    for x in b:
        rom[pc] = x & 0xFF
        pc += 1


def label(name):
    labels[name] = pc


def jr(op, name):
    emit(op, 0)
    fix.append((pc - 1, name))


# Entry point and VBlank vector.
org(0x100); emit(0x00, 0xC3, 0x50, 0x01)       # NOP; JP 0x0150
org(0x40);  emit(0xC3, 0x00, 0x10)             # VBlank: JP 0x1000

org(0x150)
emit(0xF3)                                      # DI
emit(0x31, 0xFE, 0xFF)                          # LD SP,0xFFFE
# Fill both VRAM banks with a pseudo-random sequence (D = D*5+3 each byte).
emit(0x16, 0x5A)                                # LD D,0x5A
for bank in (0, 1):
    emit(0x3E, bank, 0xE0, 0x4F)                # LD A,bank ; LDH (VBK),A
    emit(0x21, 0x00, 0x80)                      # LD HL,0x8000
    emit(0x01, 0x00, 0x20)                      # LD BC,0x2000
    label("fill%d" % bank)
    emit(0x7A, 0x87, 0x87, 0x82, 0xC6, 0x03, 0x57)  # LD A,D; A*=5; +3; LD D,A
    emit(0x22)                                  # LD (HL+),A
    emit(0x0B, 0x78, 0xB1)                      # DEC BC; LD A,B; OR C
    jr(0x20, "fill%d" % bank)                   # JR NZ
emit(0xAF, 0xE0, 0x4F)                          # VBK=0
# Fill OAM (160 bytes).
emit(0x21, 0x00, 0xFE, 0x06, 0xA0)              # LD HL,0xFE00 ; LD B,160
label("oam")
emit(0x7A, 0x87, 0x87, 0x82, 0xC6, 0x03, 0x57, 0x22, 0x05)  # next D; LD (HL+),A; DEC B
jr(0x20, "oam")
# Small hblank HDMA: ROM 0x2000 -> VRAM 0x8000, 4 blocks (writes zeros in).
emit(0x3E, 0x20, 0xE0, 0x51, 0xAF, 0xE0, 0x52, 0xE0, 0x53, 0xE0, 0x54, 0x3E, 0x83, 0xE0, 0x55)
# Window and screen on: LCDC = 0xF7 (window map 1, window on, tiles 0x8000, BG map 1, 8x16 off, OBJ on, BG on).
emit(0x3E, 0xF7, 0xE0, 0x40)
# Double speed: KEY1=1; STOP.
emit(0x3E, 0x01, 0xE0, 0x4D, 0x10, 0x00)
# VBlank interrupt on, enable interrupts.
emit(0x3E, 0x01, 0xE0, 0xFF, 0xFB)
# Main loop: churn WRAM so the CPU has work between VBlanks.
emit(0x21, 0x00, 0xC0)                          # LD HL,0xC000
label("main")
emit(0x2C, 0x7D, 0x77, 0x23, 0x7C, 0xE6, 0x1F, 0xF6, 0xC0, 0x67)  # INC L; LD A,L; LD (HL),A; INC HL; LD A,H; AND 0x1F; OR 0xC0; LD H,A (stay in WRAM 0xC000-0xDFFF)
jr(0x18, "main")                                # JR main

# VBlank handler at 0x1000: moves everything a little every frame.
org(0x1000)
emit(0xF5, 0xE5)                                # PUSH AF; PUSH HL
emit(0xF0, 0x80, 0x3C, 0xE0, 0x80)              # frame counter in HRAM 0x80: LDH A,(80); INC A; LDH (80),A
emit(0xE0, 0x43, 0x87, 0xE0, 0x42)              # SCX = n ; SCY = 2n
emit(0xF0, 0x80, 0xE6, 0x3F, 0xE0, 0x4A)        # WY = n & 63
emit(0xC6, 0x07, 0xE0, 0x4B)                    # WX = (n & 63) + 7
emit(0xF0, 0x80, 0xE6, 0x3F, 0xF6, 0x80, 0xE0, 0x68)   # BCPS = 0x80 | (n & 63), auto-increment
emit(0xF0, 0x80, 0x67, 0x87, 0x84, 0xE0, 0x69, 0xE0, 0x69)  # BCPD = 3n, twice
emit(0xF0, 0x80, 0xE6, 0x3F, 0xF6, 0x80, 0xE0, 0x6A)   # OCPS likewise
emit(0xF0, 0x80, 0xEE, 0x5A, 0xE0, 0x6B, 0xE0, 0x6B)   # OCPD = n ^ 0x5A, twice
emit(0xF0, 0x80, 0xE6, 0x7F, 0x6F, 0x26, 0xFE, 0x77)   # OAM[n & 127] = n
# Every 32nd frame toggle 8x8 / 8x16 sprites.
emit(0xF0, 0x80, 0xE6, 0x1F)
jr(0x20, "skip")
emit(0xF0, 0x40, 0xEE, 0x04, 0xE0, 0x40)
label("skip")
emit(0xE1, 0xF1, 0xD9)                          # POP HL; POP AF; RETI

for pos, name in fix:
    off = labels[name] - (pos + 1)
    assert -128 <= off <= 127, (name, off)
    rom[pos] = off & 0xFF

# Header.
rom[0x134:0x144] = b"WALNUT TEST ROM\x00"
rom[0x143] = 0x80   # CGB-supported
rom[0x147] = 0x00   # ROM only
rom[0x148] = 0x00   # 32 KiB
rom[0x149] = 0x00   # no RAM
x = 0
for i in range(0x134, 0x14D):
    x = (x - rom[i] - 1) & 0xFF
rom[0x14D] = x

out = sys.stdout
out.write("/* Generated by gen_cgb_test_rom.py; do not edit. */\n#pragma once\n#include <stddef.h>\n")
out.write("static const unsigned char kCgbTestRom[0x8000] = {\n")
for i in range(0, len(rom), 16):
    out.write("  " + ",".join("0x%02X" % b for b in rom[i:i + 16]) + ",\n")
out.write("};\n")
